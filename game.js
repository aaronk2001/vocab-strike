function startWave() {
  S.enemies = []; S.focus = null; S.salvage = [];
  S.errKey = null;                                   // fresh wave, fresh slate
  S.waveSize = Math.min(3 + Math.floor((S.wave - 1) / 2), 5);
  S.spawnLeft = S.waveSize; S.spawnT = 0.55;
}

function spawn() {
  const e = nextCard();
  const txt = e.t;
  const maxW = Math.min(330, W * 0.30);
  let fs = 15;
  let tw = measure(txt, `600 ${fs}px ${MONO}`);
  if (tw > maxW) { fs = Math.max(11, fs * maxW / tw); tw = measure(txt, `600 ${fs}px ${MONO}`); }
  const top = HUD_H + 34, bot = Math.max(top + 10, H - PROMPT_H - 34);
  // best of a few random rows, so a new ship doesn't sit on top of another
  let y = top, gap = -1;
  for (let i = 0; i < 8; i++) {
    const cy = rnd(top, bot);
    const d = Math.min(Infinity, ...S.enemies.map((o) => Math.abs(o.y - cy)));
    if (d > gap) { gap = d; y = cy; }
  }
  S.enemies.push({
    e, txt, fs, tw,
    w: tw + 46, h: 44,
    x: W + Math.max(90, tw / 2 + 30), y,
    vx: 46 * S.diff.spd * (1 + (S.wave - 1) * 0.075),
    prog: 0, born: performance.now(), wob: Math.random() * 6.28,
  });
}

function pushFloat(x, y, text, col) {
  S.floats.push({ x, y, text, col, t: 0, dur: 1.05 });
}
function burst(x, y, col, n) {
  for (let i = 0; i < n; i++) {
    const a = Math.random() * 6.283, sp = rnd(50, 330);
    S.particles.push({
      x, y, vx: Math.cos(a) * sp, vy: Math.sin(a) * sp,
      t: 0, dur: rnd(0.35, 0.8), size: rnd(1.4, 3.6), col,
    });
  }
}
function setToast(text, sub, dur, col) {
  S.toast = { text, sub: sub || '', t: 0, dur: dur || 2, col: col || C.accent3 };
}

/* ---- defend ---- */
function handleDefendChar(ch) {
  const f = S.focus;
  if (f && f.prog < f.txt.length) {
    if (eq(ch, f.txt[f.prog])) { advanceEnemy(f); return; }
    if (f.prog > 0) { mistake(ch); return; }          // locked in mid-word
  }
  // pick the nearest ship whose first character matches
  let best = null;
  for (const e of S.enemies) {
    if (e.prog === 0 && eq(ch, e.txt[0])) { if (!best || e.x < best.x) best = e; }
  }
  if (best) { S.focus = best; advanceEnemy(best); return; }
  mistake(ch);
}

function advanceEnemy(e) {
  e.prog++;
  S.adv++; S.combo++;
  S.bestCombo = Math.max(S.bestCombo, S.combo);
  S.score += 1 * mult();
  sfx.key();
  if (e.prog >= e.txt.length) killEnemy(e);
}

function killEnemy(e) {
  const i = S.enemies.indexOf(e);
  if (i < 0) return;
  S.enemies.splice(i, 1);
  if (S.focus === e) S.focus = null;
  S.killed++;
  S.salvageCount++;
  S.salvage.push(e.e);
  const gain = Math.round(60 * mult() + (W - e.x) * 0.05);
  S.score += gain;
  S.beams.push({ x1: PX, y1: midY(), x2: e.x, y2: e.y, t: 0, dur: 0.16 });
  burst(e.x, e.y, C.cyan, 26);
  burst(e.x, e.y, C.accent, 14);
  pushFloat(e.x, e.y - 30, '+' + gain, C.pos);
  S.flash = 0.10; S.flashCol = C.cyan;
  sfx.kill();
  if (e.prog >= e.txt.length && e.txt.length > 12) sfx.lock();
}

function mistake(ch) {
  S.errKey = ch == null ? '?' : ch;   // committed mistake — Backspace clears it
  S.err++;
  S.combo = 0;
  S.shake = Math.min(11, S.shake + 5);
  S.flash = 0.12; S.flashCol = C.danger;
  sfx.err();
}

/* clear a committed mistake — the word accepts keys again after this */
function clearMistake() {
  if (!S.errKey) return;
  S.errKey = null;
  sfx.key();
}

function hurt() {
  S.hp--; S.combo = 0;
  S.shake = 16;
  S.flash = 0.30; S.flashCol = C.danger;
  S.beams.push({ x1: 0, y1: midY(), x2: PX, y2: midY(), t: 0, dur: 0.2, red: true });
  sfx.hurt();
  if (S.hp <= 0) gameOver();
}

const midY = () => (HUD_H + 10 + (H - PROMPT_H - 10)) / 2;

function updateDefend(dt) {
  S.spawnT -= dt;
  if (S.spawnLeft > 0 && S.spawnT <= 0) {
    spawn(); S.spawnLeft--;
    S.spawnT = Math.max(0.7, (2.0 - S.wave * 0.07)) * S.diff.spawn;
  }
  for (let i = S.enemies.length - 1; i >= 0; i--) {
    const e = S.enemies[i];
    e.x -= e.vx * dt;
    e.wob += dt * 2;
    if (e.x - e.w / 2 <= PX + 22) {
      S.enemies.splice(i, 1);
      if (S.focus === e) S.focus = null;
      S.salvageCount++; S.salvage.push(e.e);               // captured on impact, not a kill
      burst(e.x, e.y, C.danger, 22);
      pushFloat(PX, midY() - 34, '-1 HULL', C.danger);
      hurt();
      if (S.mode !== 'defend') return;
    }
  }
  if (S.focus && !S.enemies.includes(S.focus)) S.focus = null;
  if (S.spawnLeft === 0 && S.enemies.length === 0 && S.mode === 'defend') beginDecode();
}

function beginDecode() {
  S.mode = 'decode'; S.scene = 'decode';
  S.queue = shuffle(S.salvage);
  S.qi = 0; S.decodedBefore = S.decoded;
  setToast('WAVE ' + S.wave + ' CLEARED', S.queue.length + ' signals salvaged — type the definitions', 2.1, C.pos);
  sfx.wave();
  loadCard();
}

function loadCard() {
  S.card = S.queue[S.qi];
  S.cardProg = 0;
  S.cardState = 'typing';
  S.errKey = null;                                   // each card starts clean
  S.cardLimit = (6 + 0.25 * S.card.d.length) * S.diff.timer;
  S.cardT = S.cardLimit;
}

function advanceCard() {
  S.cardProg++;
  S.adv++;
  S.combo++;
  S.bestCombo = Math.max(S.bestCombo, S.combo);
  S.score += 2 * mult();
  sfx.key();
  if (S.cardProg >= S.card.d.length) {
    const bonus = Math.round((S.cardT / S.cardLimit) * 140);
    const gain = Math.round(150 * mult()) + bonus;
    S.score += gain;
    S.decoded++;
    S.cardState = 'done'; S.cardHold = 1.7;
    // float above the panel so it never lands on the result banner
    const b = decodeBox();
    pushFloat(W / 2, b.py - 34, '+' + gain + (bonus ? '  speed +' + bonus : ''), C.pos);
    S.flash = 0.14; S.flashCol = C.pos;
    sfx.good();
  }
}

function failCard() {
  S.missed++; S.combo = 0;
  S.cardState = 'miss'; S.cardHold = 2.1;
  S.flash = 0.20; S.flashCol = C.warn;
  sfx.bad();
}

function skipCard() {
  if (S.cardState !== 'typing') return;
  S.missed++; S.combo = 0;
  S.cardState = 'skip'; S.cardHold = 0.9;
  sfx.bad();
}

function updateDecode(dt) {
  if (S.cardState === 'typing') {
    S.cardT -= dt;
    if (S.cardT <= 0) { S.cardT = 0; failCard(); }
  } else if (S.cardState === 'done' || S.cardState === 'miss' || S.cardState === 'skip') {
    S.cardHold -= dt;
    if (S.cardHold <= 0) nextCardInQueue();
  }
}
function nextCardInQueue() {
  S.qi++;
  if (S.qi >= S.queue.length) endDecode();
  else loadCard();
}

function endDecode() {
  const ok = S.decoded - S.decodedBefore, n = S.queue.length;
  S.wave++;
  S.mode = 'defend'; S.scene = 'defend';
  startWave();
  setToast('WAVE ' + S.wave, 'hull ' + S.hp + '/' + S.maxHp + ' — ' + ok + '/' + n + ' definitions banked', 1.9, C.accent3);
}

function gameOver() {
  S.mode = 'over'; S.scene = null;
  show(ctlEl, false); show(pauseEl, false);
  const a = Math.round(acc()), p = Math.round(wpm());
  $('oS').textContent = S.score.toLocaleString();
  $('oW').textContent = S.wave;
  $('oP').textContent = p;
  $('oA').textContent = a + '%';
  $('oK').textContent = S.killed;
  $('oD').textContent = S.decoded;
  $('oC').textContent = S.bestCombo;
  $('oM').textContent = S.missed;
  $('verdict').textContent = S.wave >= 8 ? 'Glossary Master' : S.wave >= 5 ? 'Deep Run' : S.wave >= 3 ? 'Holding The Line' : 'Hull Breach';
  const vc = S.wave >= 5 ? '16,185,129' : S.wave >= 3 ? '245,158,11' : '244,63,94';
  $('verdict').style.cssText = `background:rgba(${vc},.15);color:rgb(${vc});border:1px solid rgba(${vc},.4)`;
  saveBest(p, a);
  sfx.over();
  show(overEl, true);
}

