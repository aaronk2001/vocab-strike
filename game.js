/* =====================================================================
   VOCAB STRIKE — a ZType-style typing game over a bundled glossary.

   Two phases:
     DEFEND  enemy ships drift in from the right carrying a TERM.
             Type the term exactly to destroy the ship.
             A wrong key locks the word until you press Backspace.
     DECODE  once the wave is clear, type each salvaged DEFINITION
             before its timer runs out.

   Data comes from data.js (generated by build_data.py from the Ascent
   career-planner YAML glossaries). Everything is plain ASCII already, so
   what is drawn is exactly what must be typed.
   ===================================================================== */
