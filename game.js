const KEY = 'vocabstrike.v1';
function loadBest() {
  try { return JSON.parse(localStorage.getItem(KEY)) || {}; } catch (e) { return {}; }
}
function saveBest(p, a) {
  const b = loadBest();
  const n = {
    score: Math.max(b.score || 0, S.score),
    wave:  Math.max(b.wave || 0, S.wave),
    wpm:   Math.max(b.wpm || 0, p),
    acc:   Math.max(b.acc || 0, a),
    runs:  (b.runs || 0) + 1,
  };
  try { localStorage.setItem(KEY, JSON.stringify(n)); } catch (e) {}
  paintBest();
  $('oBest').innerHTML = `Personal best &middot; <b>${n.score.toLocaleString()}</b> pts &middot; wave <b>${n.wave}</b> &middot; <b>${n.wpm}</b> WPM &middot; <b>${n.acc}%</b>`;
}
function paintBest() {
  const b = loadBest();
  $('best').innerHTML = b.score
    ? `Personal best &middot; <b>${b.score.toLocaleString()}</b> pts &middot; wave <b>${b.wave}</b> &middot; <b>${b.wpm}</b> WPM &middot; <b>${b.acc}%</b> accuracy`
    : `No runs yet.`;
}

