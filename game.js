  bad()     { tone(300, 0.22, 'sawtooth', 0.05, 120); },
  hurt()    { noise(0.4, 0.24, 700); tone(90, 0.3, 'sawtooth', 0.07, 45); },
  wave()    { [440, 587, 740].forEach((f, i) => setTimeout(() => tone(f, 0.16, 'triangle', 0.05), i * 90)); },
  over()    { [440, 330, 247, 165].forEach((f, i) => setTimeout(() => tone(f, 0.34, 'sawtooth', 0.06), i * 150)); },
