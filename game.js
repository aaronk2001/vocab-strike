function drawTyped(txt, prog, x, y, font, o) {
  o = o || {};
  ctx.font = font;
  const m = font.match(/(\d+(?:\.\d+)?)px/);
  const fs = m ? parseFloat(m[1]) : 16;
  let cx = x;
  for (let i = 0; i < txt.length; i++) {
    const ch = txt[i];
    const w = ctx.measureText(ch).width;
    if (i === prog && o.caret) {
      ctx.fillStyle = o.caretBg || 'rgba(99,102,241,.55)';
      rr(cx - 1, y - fs * 0.84, w + 2, fs * 1.05, 3); ctx.fill();
    }
    ctx.fillStyle = i < prog ? (o.done || C.pos) : (i === prog ? (o.cur || C.fg) : (o.todo || C.muted));
    ctx.fillText(ch, cx, y);
    cx += w;
  }
  return cx;
}
function widthOf(txt, font) { ctx.font = font; let w = 0; for (const c of txt) w += ctx.measureText(c).width; return w; }

function wrap(text, font, maxW) {
  ctx.font = font;
  const words = text.split(' ');
  const lines = [];
  let cur = '', start = 0;
  for (const w of words) {
    const test = cur ? cur + ' ' + w : w;
    if (cur && ctx.measureText(test).width > maxW) {
      lines.push({ s: start, n: cur.length });
      start = start + cur.length + 1;
      cur = w;
    } else cur = test;
  }
  if (cur) lines.push({ s: start, n: cur.length });
  return lines;
}

function pill(x, y, text, col, font) {
  ctx.font = font || `600 10px ${SANS}`;
  const w = ctx.measureText(text).width + 16;
  rr(x, y, w, 19, 9.5);
  ctx.fillStyle = col + '22'; ctx.fill();
  ctx.strokeStyle = col + '55'; ctx.lineWidth = 1; ctx.stroke();
  ctx.fillStyle = col; ctx.textAlign = 'left'; ctx.textBaseline = 'middle';
  ctx.fillText(text, x + 8, y + 10.5);
  ctx.textBaseline = 'alphabetic';
  return w;
}

