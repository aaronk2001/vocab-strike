function pause() {
  if (S.mode !== 'defend' && S.mode !== 'decode') return;
  S.pausedFrom = S.mode; S.mode = 'pause';
  show(pauseEl, true);
}
function resume() {
  if (S.mode !== 'pause') return;
  S.mode = S.pausedFrom; show(pauseEl, false);
}
function toMenu() {
  S.mode = 'menu'; S.scene = null;
  show(menuEl, true); show(overEl, false); show(pauseEl, false); show(ctlEl, false);
  paintBest();
}
function toggleMute() {
  S.muted = !S.muted;
  $('btnMute').innerHTML = S.muted ? '&#128263;' : '&#128266;';
}

/* Which keys this mode consumes. Everything else falls through to the browser. */
function consumes(k) {
  switch (S.mode) {
    case 'menu':   return k === 'Enter' || k === ' ' || k === 'm' || k === 'M';
    case 'over':   return k === 'Enter' || k === ' ' || k === 'Escape';
    case 'pause':  return k === 'Escape' || k === 'Enter' || k === 'q' || k === 'Q' || k === 'm' || k === 'M';
    case 'defend': return k === 'Escape' || k === 'Backspace' || k.length === 1;
    case 'decode': return k === 'Escape' || k === 'Enter' || k === 'Backspace' || k.length === 1;
    default:       return false;
  }
}

/* Single entry point for all keystrokes — reachable from the keyboard and
   from the VS debug handle so tests can drive real gameplay. */
function pressKey(k) {
  switch (S.mode) {
    case 'menu':
      if (k === 'Enter' || k === ' ') startGame();
      else if (k === 'm' || k === 'M') toggleMute();
      return;
    case 'over':
      if (k === 'Enter' || k === ' ') startGame();
      else if (k === 'Escape') toMenu();
      return;
    case 'pause':
      if (k === 'Escape' || k === 'Enter') resume();
      else if (k === 'q' || k === 'Q') toMenu();
      else if (k === 'm' || k === 'M') toggleMute();
      return;
    case 'defend':
      if (k === 'Escape') { pause(); return; }
      if (k === 'Backspace') { clearMistake(); return; }
      if (k.length === 1) { if (S.errKey) return; handleDefendChar(k); }   // pending mistake: ignore letters
      return;
    case 'decode':
      if (k === 'Escape') { pause(); return; }
      if (k === 'Backspace') { clearMistake(); return; }
      if (k === 'Enter') { skipCard(); return; }
      if (k.length === 1) {
        if (S.cardState === 'typing') {
          if (S.errKey) return;                       // pending mistake: ignore letters
          if (eq(k, S.card.d[S.cardProg])) advanceCard(); else mistake(k);
        }
      }
      return;
  }
}

